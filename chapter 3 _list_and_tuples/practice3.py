# This program shows a list and a tuple

# Create a list (lists can be changed)
fruits = ["apple", "banana", "orange"]

# Print the full list
print("Fruits list:", fruits)

# Access and print the first item in the list
print("First fruit:", fruits[0])

# Create a tuple (tuples cannot be changed)
colors = ("red", "green", "blue")

# Print the full tuple
print("Colors tuple:", colors)

# Access and print the second item in the tuple
print("Second color:", colors[1])